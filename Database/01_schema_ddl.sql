-- 1. TABEL PENGGUNA
CREATE TABLE pengguna (
    id_pengguna NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nama_lengkap VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    CONSTRAINT pk_pengguna PRIMARY KEY (id_pengguna)
);

-- 2. TABEL PROFIL PENGGUNA
CREATE TABLE profil_pengguna (
    id_pengguna NUMBER,
    universitas VARCHAR2(100),
    jurusan VARCHAR2(100),
    semester NUMBER,
    target_lulus DATE,
    tingkat_awal VARCHAR2(30) NOT NULL,
    jam_belajar_harian NUMBER NOT NULL,
    waktu_pilihan VARCHAR2(30) NOT NULL,
    cita_cita_karier VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_profil_pengguna PRIMARY KEY (id_pengguna),
    CONSTRAINT fk_profil_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
);

-- 3. TABEL BIDANG IT
CREATE TABLE bidang_it (
    id_bidang NUMBER,
    nama_bidang VARCHAR2(100) NOT NULL,
    deskripsi VARCHAR2(255),
    CONSTRAINT pk_bidang_it PRIMARY KEY (id_bidang)
);

-- 4. TABEL CHECK-IN HARIAN
CREATE TABLE checkin_harian (
    id_checkin NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pengguna NUMBER,
    tanggal DATE DEFAULT SYSDATE NOT NULL,
    catatan VARCHAR2(255),
    CONSTRAINT pk_checkin_harian PRIMARY KEY (id_checkin),
    CONSTRAINT fk_checkin_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
);

-- 5. TABEL MATERI
CREATE TABLE materi (
    id_materi NUMBER,
    id_bidang NUMBER,
    judul_materi VARCHAR2(150) NOT NULL,
    tingkat VARCHAR2(30) NOT NULL,
    estimasi_jam NUMBER NOT NULL,
    urutan NUMBER NOT NULL,
    deskripsi VARCHAR2(255),
    CONSTRAINT pk_materi PRIMARY KEY (id_materi),
    CONSTRAINT fk_materi_bidang FOREIGN KEY (id_bidang)
        REFERENCES bidang_it(id_bidang)
);

-- 6. TABEL JADWAL BELAJAR
CREATE TABLE jadwal_belajar (
    id_jadwal NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pengguna NUMBER,
    id_materi NUMBER,
    tanggal_jadwal DATE NOT NULL,
    durasi_jam NUMBER NOT NULL,
    status VARCHAR2(30) DEFAULT 'TERJADWAL' NOT NULL,
    CONSTRAINT pk_jadwal_belajar PRIMARY KEY (id_jadwal),
    CONSTRAINT fk_jadwal_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna),
    CONSTRAINT fk_jadwal_materi FOREIGN KEY (id_materi)
        REFERENCES materi(id_materi)
);

-- 7. TABEL HASIL BELAJAR
CREATE TABLE hasil_belajar (
    id_hasil NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_jadwal NUMBER,
    id_pengguna NUMBER,
    catatan_hasil VARCHAR2(255),
    tanggal_selesai DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_hasil_belajar PRIMARY KEY (id_hasil),
    CONSTRAINT fk_hasil_jadwal FOREIGN KEY (id_jadwal)
        REFERENCES jadwal_belajar(id_jadwal),
    CONSTRAINT fk_hasil_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
);

-- 8. TABEL PENGINGAT
CREATE TABLE pengingat (
    id_pengingat NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pengguna NUMBER,
    pesan VARCHAR2(255) NOT NULL,
    waktu_pengingat VARCHAR2(10) NOT NULL,
    status VARCHAR2(20) DEFAULT 'AKTIF' NOT NULL,
    CONSTRAINT pk_pengingat PRIMARY KEY (id_pengingat),
    CONSTRAINT fk_pengingat_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
);

-- 9. TABEL LANGKAH KARIER
CREATE TABLE langkah_karier (
    id_langkah NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pengguna NUMBER,
    judul_langkah VARCHAR2(150) NOT NULL,
    kategori VARCHAR2(50) NOT NULL,
    status VARCHAR2(20) DEFAULT 'BELUM' NOT NULL,
    CONSTRAINT pk_langkah_karier PRIMARY KEY (id_langkah),
    CONSTRAINT fk_langkah_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
);

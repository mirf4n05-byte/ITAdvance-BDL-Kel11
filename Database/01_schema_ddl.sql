


-- 1. Tabel USERS
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);

-- 2. Tabel USER_PREFERENCES
CREATE TABLE USER_PREFERENCES (
    PREFERENCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    INTEREST_FIELD VARCHAR2(100) NOT NULL,
    SKILL_LEVEL VARCHAR2(30) NOT NULL,
    HOURS_PER_WEEK NUMBER(3) NOT NULL,
    GRADUATION_DATE DATE,

    CONSTRAINT PK_USER_PREFERENCES PRIMARY KEY (PREFERENCE_ID),
    CONSTRAINT UQ_PREF_USER UNIQUE (USER_ID),
    CONSTRAINT FK_PREF_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT CK_PREF_HOURS CHECK (HOURS_PER_WEEK > 0)
);

-- 3. Tabel LEARNING_MODULES
CREATE TABLE LEARNING_MODULES (
    MODULE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITLE VARCHAR2(150) NOT NULL,
    FIELD VARCHAR2(100) NOT NULL,
    SKILL_LEVEL VARCHAR2(30) NOT NULL,
    STEP_ORDER NUMBER NOT NULL,
    ESTIMATED_HOURS NUMBER(4,1),
    DESCRIPTION VARCHAR2(1000),

    CONSTRAINT PK_LEARNING_MODULES PRIMARY KEY (MODULE_ID)
);

-- 4. Tabel USER_SCHEDULES
CREATE TABLE USER_SCHEDULES (
    SCHEDULE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    MODULE_ID NUMBER NOT NULL,
    SCHEDULED_DATE DATE NOT NULL,
    IS_COMPLETED NUMBER(1) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_USER_SCHEDULES PRIMARY KEY (SCHEDULE_ID),
    CONSTRAINT FK_SCHEDULE_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT FK_SCHEDULE_MODULE FOREIGN KEY (MODULE_ID)
        REFERENCES LEARNING_MODULES(MODULE_ID),
    CONSTRAINT CK_SCHEDULE_STATUS CHECK (IS_COMPLETED IN (0,1))
);

-- 5. Tabel DAILY_CHECKINS
CREATE TABLE DAILY_CHECKINS (
    CHECKIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    CHECKIN_DATE DATE DEFAULT TRUNC(SYSDATE) NOT NULL,

    CONSTRAINT PK_DAILY_CHECKINS PRIMARY KEY (CHECKIN_ID),
    CONSTRAINT FK_CHECKIN_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT UQ_DAILY_CHECKIN UNIQUE (USER_ID, CHECKIN_DATE)
);

-- 6. Tabel CAREER_CHECKLISTS
CREATE TABLE CAREER_CHECKLISTS (
    ITEM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TASK_NAME VARCHAR2(200) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    MONTHS_BEFORE_GRAD NUMBER,

    CONSTRAINT PK_CAREER_CHECKLISTS PRIMARY KEY (ITEM_ID)
);

-- 7. Tabel USER_CAREER_PROGRESS
CREATE TABLE USER_CAREER_PROGRESS (
    PROGRESS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    ITEM_ID NUMBER NOT NULL,
    IS_COMPLETED NUMBER(1) DEFAULT 0 NOT NULL,
    COMPLETED_AT TIMESTAMP,

    CONSTRAINT PK_USER_CAREER_PROGRESS PRIMARY KEY (PROGRESS_ID),
    CONSTRAINT FK_PROGRESS_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT FK_PROGRESS_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES CAREER_CHECKLISTS(ITEM_ID),
    CONSTRAINT CK_PROGRESS_STATUS CHECK (IS_COMPLETED IN (0,1)),
    CONSTRAINT UQ_USER_ITEM UNIQUE (USER_ID, ITEM_ID)
);
